export function renderSocialIcon(iconKey: string, size = 22, className?: string) {
  switch (iconKey) {
    case "website":
      return <Globe size={size} className={className} />;
    case "radio":
      return <Radio size={size} className={className} />;
    case "youtube":
      return <YoutubeIcon size={size} className={className} />;
    case "tiktok":
      return <TikTokIcon size={size} className={className} />;
    case "instagram":
      return <InstagramIcon size={size} className={className} />;
    case "x":
      return <XIcon size={size} className={className} />;
    case "whatsapp":
      return <WhatsAppIcon size={size} className={className} />;
    default:
      return <Link2 size={size} className={className} />;
  }
}
